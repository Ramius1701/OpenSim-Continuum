        private CoverageMode ParseCoverageMode(string value)
        {
            string normalized = (value ?? string.Empty).Trim();

            if (string.Equals(normalized, "Region", StringComparison.OrdinalIgnoreCase))
                return CoverageMode.Region;

            if (string.Equals(normalized, "ActiveArea", StringComparison.OrdinalIgnoreCase)
                || string.Equals(normalized, "Active-Area", StringComparison.OrdinalIgnoreCase)
                || string.Equals(normalized, "Active_Area", StringComparison.OrdinalIgnoreCase))
            {
                return CoverageMode.ActiveArea;
            }

            m_log.WarnFormat(
                "[WEATHER]: CoverageMode '{0}' is invalid; using Region coverage.",
                normalized);
            return CoverageMode.Region;
        }

        private UUID ReadTexture(IConfig config, string key, UUID fallback)
        {
            string value = config.GetString(key, string.Empty).Trim();
            if (string.IsNullOrEmpty(value))
                return fallback;

            if (UUID.TryParse(value, out UUID texture))
                return texture;

            m_log.WarnFormat("[WEATHER]: {0} '{1}' is not a valid UUID; using fallback texture {2}.", key, value, fallback);
            return fallback;
        }

        private WeatherKind CurrentWeather()
        {
            lock (m_sync)
                return m_currentWeather;
        }

        private static bool IsPrecipitationWeather(WeatherKind weather)
        {
            return weather == WeatherKind.Rain || weather == WeatherKind.Storm || weather == WeatherKind.Snow;
        }

        private void SendReply(IClientAPI client, string message)
        {
            client.SendChatMessage(
                message,
                (byte)ChatTypeEnum.Owner,
                Vector3.Zero,
                "Weather",
                UUID.Zero,
                UUID.Zero,
                (byte)ChatSourceType.Object,
                (byte)ChatAudibleLevel.Fully);
        }

        private static float Clamp(float value, float min, float max)
        {
            if (value < min)
                return min;
            if (value > max)
                return max;
            return value;
        }

        private static int Clamp(int value, int min, int max)
        {
            if (value < min)
                return min;
            if (value > max)
                return max;
            return value;
        }
