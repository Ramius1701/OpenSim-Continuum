        private static bool IsWeatherCommand(string request)
        {
            string[] tokens = CommandTokens(request);
            return tokens.Length > 0 && (tokens[0] == "weather" || tokens[0] == "meteo");
        }

        private bool TryResolveWeather(string request, out WeatherKind weather)
        {
            string token = WeatherToken(request);
            switch (token)
            {
                case "clear":
                case "stop":
                case "asciutto":
                    weather = WeatherKind.Clear;
                    return true;

                case "sunny":
                case "sun":
                case "sereno":
                case "sole":
                    weather = WeatherKind.Sunny;
                    return true;

                case "storm":
                case "temporale":
                case "tempesta":
                    weather = WeatherKind.Storm;
                    return true;

                case "snow":
                case "neve":
                case "nevica":
                    weather = WeatherKind.Snow;
                    return true;

                case "rain":
                case "pioggia":
                case "piove":
                    weather = WeatherKind.Rain;
                    return true;

                default:
                    weather = WeatherKind.Clear;
                    return false;
            }
        }

        private static bool IsStatusCommand(string request)
        {
            string[] tokens = CommandTokens(request);
            if (tokens.Length == 0)
                return false;

            if ((tokens[0] == "weather" || tokens[0] == "meteo") && tokens.Length == 1)
                return true;

            string token = WeatherToken(request);
            return token == "status" || token == "stato";
        }

        private static string WeatherToken(string request)
        {
            string[] tokens = CommandTokens(request);
            if (tokens.Length == 0)
                return string.Empty;

            if (tokens[0] == "weather" || tokens[0] == "meteo")
                return tokens.Length > 1 ? tokens[1] : string.Empty;

            return tokens[0];
        }

        private static string[] CommandTokens(string request)
        {
            return (request ?? string.Empty)
                .Trim()
                .ToLower(CultureInfo.InvariantCulture)
                .Split(new[] { ' ', '\t' }, StringSplitOptions.RemoveEmptyEntries);
        }

