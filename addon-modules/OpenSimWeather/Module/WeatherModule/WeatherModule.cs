        public void Initialise(IConfigSource source)
        {
            IConfig config = source.Configs["Weather"];
            if (config == null)
            {
                m_enabled = false;
                m_log.Info("[WEATHER]: No [Weather] configuration found; module remains disabled.");
                return;
            }

            m_enabled = config.GetBoolean("Enabled", false);
            if (!m_enabled)
            {
                m_log.Info("[WEATHER]: Module disabled by [Weather] Enabled=false.");
                return;
            }

            m_commandChannel = config.GetInt("CommandChannel", 89);
            if (m_commandChannel == 0)
            {
                m_log.Warn("[WEATHER]: CommandChannel=0 would expose weather commands in public chat; using channel 89 instead.");
                m_commandChannel = 89;
            }

            m_estateManagerOnly = config.GetBoolean("EstateManagerOnly", true);
            m_coverageMode = ParseCoverageMode(config.GetString("CoverageMode", "Region"));
            m_emitterGrid = Clamp(config.GetInt("EmitterGrid", 8), 0, 128);
            m_emitterSpacingMeters = Clamp(config.GetFloat("EmitterSpacingMeters", 24f), 6f, 512f);
            m_maxEmitters = Clamp(config.GetInt("MaxEmitters", 384), 1, 16384);
            m_activeAreaRadiusMeters = Clamp(config.GetFloat("ActiveAreaRadiusMeters", 96f), 16f, 1024f);
            m_activeAreaRefreshSeconds = Clamp(config.GetInt("ActiveAreaRefreshSeconds", 3), 1, 300);
            m_emitterRadiusScale = Clamp(config.GetFloat("EmitterRadiusScale", 0.62f), 0.1f, 1.25f);
            m_emitterHeight = Clamp(config.GetFloat("EmitterHeight", 18f), 4f, 4096f);
            m_intensity = Clamp(config.GetFloat("Intensity", 1f), 0.1f, 10f);
            m_rainTexture = ReadTexture(config, "RainTexture", Util.BLANK_TEXTURE_UUID);
            m_stormTexture = ReadTexture(config, "StormTexture", m_rainTexture);
            m_snowTexture = ReadTexture(config, "SnowTexture", Util.BLANK_TEXTURE_UUID);
            m_lightningTexture = ReadTexture(config, "LightningTexture", Util.BLANK_TEXTURE_UUID);

            m_adjustClouds = config.GetBoolean("AdjustEnvironment", config.GetBoolean("AdjustClouds", false));
            m_allowPersistentEnvironmentChanges = config.GetBoolean("AllowPersistentEnvironmentChanges", false);
            m_restoreCloudsOnClear = config.GetBoolean("RestoreCloudsOnClear", true);
            if (m_adjustClouds && !m_allowPersistentEnvironmentChanges)
            {
                m_adjustClouds = false;
                m_log.Warn(
                    "[WEATHER]: AdjustEnvironment=true ignored because AllowPersistentEnvironmentChanges is not true. "
                    + "OpenSim stores LightShare/EEP region environment changes; enable the acknowledgement only after reading the module documentation.");
            }

            m_adjustWind = config.GetBoolean("AdjustWind", false);
            m_restoreWindOnClear = config.GetBoolean("RestoreWindOnClear", true);
            m_windDirectionDegrees = config.GetFloat("WindDirectionDegrees", 70f);
            m_windDirectionVarianceDegrees = Math.Max(0f, config.GetFloat("WindDirectionVarianceDegrees", 18f));
            m_rainWindStrength = Math.Max(0f, config.GetFloat("RainWindStrength", 0.45f));
            m_stormWindStrength = Math.Max(0f, config.GetFloat("StormWindStrength", 1.35f));
            m_snowWindStrength = Math.Max(0f, config.GetFloat("SnowWindStrength", 0.22f));

            m_avoidCoveredAreas = config.GetBoolean("AvoidCoveredAreas", true);
            m_coverProbeHeight = Clamp(config.GetFloat("CoverProbeHeight", 256f), 8f, 4096f);
            m_coverProbeGrid = Clamp(config.GetInt("CoverProbeGrid", 3), 1, 7);
            if ((m_coverProbeGrid & 1) == 0)
                m_coverProbeGrid++;
            m_minOpenSkyFraction = Clamp(config.GetFloat("MinimumOpenSkyFraction", 0.67f), 0f, 1f);
            m_suppressAroundCoveredAvatars = config.GetBoolean("SuppressAroundCoveredAvatars", true);
            m_coverIncludesPhantomPrims = config.GetBoolean("CoverIncludesPhantomPrims", false);
            m_coverMaxHits = Clamp(config.GetInt("CoverMaxHits", 32), 1, 128);
            m_useExclusionVolumes = config.GetBoolean("UseExclusionVolumes", true);
            m_exclusionObjectName = config.GetString("ExclusionObjectName", "Weather Exclusion").Trim();
            m_exclusionRefreshSeconds = Clamp(config.GetInt("ExclusionRefreshSeconds", 30), 5, 3600);
            m_cleanupGeneratedObjectsOnStartup = config.GetBoolean("CleanupGeneratedObjectsOnStartup", true);
            if (string.IsNullOrEmpty(m_exclusionObjectName))
                m_useExclusionVolumes = false;

            m_lightningEnabled = config.GetBoolean("LightningEnabled", true);
            m_lightningMinDelayMS = Clamp(config.GetInt("LightningMinDelayMS", 7000), 1000, 3600000);
            m_lightningMaxDelayMS = Clamp(config.GetInt("LightningMaxDelayMS", 18000), m_lightningMinDelayMS, 3600000);

            m_thunderEnabled = config.GetBoolean("ThunderEnabled", false);
            m_thunderVolume = Clamp(config.GetFloat("ThunderVolume", 1f), 0f, 1f);
            m_thunderSound = UUID.Zero;
            string thunderSound = config.GetString("ThunderSound", string.Empty).Trim();
